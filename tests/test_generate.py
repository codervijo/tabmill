from __future__ import annotations

import json
import shutil
from pathlib import Path

import pytest

from tabmill import generate, registry, sync, workspace
from tabmill.config import TOOL_DIR, Config

SLUG = "save-page-pdf-md"


@pytest.fixture
def with_recipe(cfg: Config) -> Config:
    shutil.copytree(TOOL_DIR / "recipes" / SLUG, cfg.tool_dir / "recipes" / SLUG)
    return cfg


def test_extension_files_combine_template_and_generated(with_recipe: Config) -> None:
    files = generate.extension_files(with_recipe.tool_dir, SLUG)
    assert "src/entrypoints/popup/index.html" in files  # .tmpl rendered
    assert (
        b"<title>Save Page as Markdown or PDF</title>" in files["src/entrypoints/popup/index.html"]
    )
    manifest = json.loads(files["manifest.gen.json"])
    assert manifest["permissions"] == ["activeTab", "scripting", "storage"]
    pkg = json.loads(files["package.json"])
    assert pkg["version"] == "0.1.0" and "wxt" in pkg["devDependencies"]
    assert pkg["dependencies"] == {"@mozilla/readability": "^0.6.0", "turndown": "^7.2.4"}
    assert "@types/turndown" in pkg["devDependencies"]
    assert "src/entrypoints/print/main.ts" in files  # recipe-only entrypoint
    config_ts = files["src/generated/config.ts"].decode()
    assert "utm_campaign=save-page-pdf-md" in config_ts
    assert "utm_source=save-page-pdf-md" in config_ts
    assert files["README.md"].decode().startswith("<!-- generated by tabmill")


def test_recipe_file_overrides_template_file(with_recipe: Config) -> None:
    feature = with_recipe.tool_dir / "recipes" / SLUG / "src" / "feature" / "index.ts"
    feature.write_text("export function mount() {}\n")
    files = generate.extension_files(with_recipe.tool_dir, SLUG)
    assert files["src/feature/index.ts"] == b"export function mount() {}\n"
    assert "extension.yaml" not in files


def test_missing_recipe_names_fix(cfg: Config) -> None:
    with pytest.raises(generate.RecipeError, match="create it in the tabmill repo"):
        generate.load_recipe(cfg.tool_dir, "nope")


def test_invalid_recipe_reports_errors(with_recipe: Config) -> None:
    path = with_recipe.tool_dir / "recipes" / SLUG / "extension.yaml"
    path.write_text(path.read_text().replace("template: popup", "template: toolbar"))
    with pytest.raises(generate.RecipeError, match="template"):
        generate.load_recipe(with_recipe.tool_dir, SLUG)


def test_template_stub_used_when_recipe_has_no_feature(with_recipe: Config) -> None:
    import shutil as _shutil

    _shutil.rmtree(with_recipe.tool_dir / "recipes" / SLUG / "src")
    files = generate.extension_files(with_recipe.tool_dir, SLUG)
    assert b"Feature not implemented yet." in files["src/feature/index.ts"]


def test_registered_extension_is_synced_and_drift_guarded(with_recipe: Config) -> None:
    ws = with_recipe.workspace
    ws.mkdir(parents=True)
    registry.upsert(ws, SLUG, {"version": "0.1.0", "status": "generated"})
    r = sync.sync(ws, workspace.managed_files(with_recipe))
    assert f"extensions/{SLUG}/wxt.config.ts" in r.installed
    target = ws / "extensions" / SLUG / "src" / "feature" / "index.ts"
    target.write_text("hand edit")
    assert sync.sync(ws, workspace.managed_files(with_recipe)).drift == [
        f"extensions/{SLUG}/src/feature/index.ts"
    ]


def test_with_utm_appends_to_existing_query() -> None:
    url = generate.with_utm("https://x.dev/a?b=1", source="s", medium="m", campaign="c")
    assert url == "https://x.dev/a?b=1&utm_source=s&utm_medium=m&utm_campaign=c"


def test_registry_upsert_is_idempotent(tmp_path: Path) -> None:
    assert registry.upsert(tmp_path, "a", {"version": "1"})
    assert not registry.upsert(tmp_path, "a", {"version": "1"})
    assert registry.read(tmp_path)["extensions"]["a"] == {"store_id": None, "version": "1"}
