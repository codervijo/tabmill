"""Tool page (`ship`, `advanced landing`; D-033): brief for the page on the portfolio site,
and recording it once live. tabmill never writes into the site repo — a Claude session there
writes the page."""

from __future__ import annotations

import re
from pathlib import Path
from typing import Any

import httpx

from . import extension, generate, hub, listing

SITES_DIR = Path("~/work/projects/sites").expanduser()
BRIEF_FILE = "landing-brief.md"
STORE_DETAIL = hub.STORE_DETAIL


def landing_url(ext: dict[str, Any]) -> str:
    path = str(ext.get("landing_path") or "").strip()
    if not path:
        first = (ext.get("target_keywords") or [ext["slug"]])[0]
        path = "/" + re.sub(r"[^a-z0-9]+", "-", str(first).lower()).strip("-")
    if not path.startswith("/"):
        path = "/" + path
    return f"https://{ext['portfolio_site']}{path}"


def site_dir(ext: dict[str, Any]) -> Path:
    return SITES_DIR / str(ext["portfolio_site"])


def store_link(ext: dict[str, Any], store_id: str | None) -> str | None:
    if not store_id:
        return None
    return generate.with_utm(
        f"{STORE_DETAIL}/{store_id}",
        source=str(ext["portfolio_site"]),
        medium="landing",
        campaign=str(ext["utm_campaign"]),
    )


def brief(ext: dict[str, Any], store_id: str | None, listing_md: str | None) -> str:
    url = landing_url(ext)
    keywords = list(ext.get("target_keywords") or [])
    perms = "\n".join(
        f"- `{p['name']}` — {p['justification']}"
        for key in ("permissions", "optional_permissions", "host_permissions")
        for p in ext.get(key) or []
    )
    link = store_link(ext, store_id)
    install = (
        f"Install link (UTM-tagged): {link}"
        if link
        else "Not in the Chrome Web Store yet — show “Coming soon”, no install button, and link "
        f"the hub page instead. Re-run `tabmill ship {ext['slug']}` after it's published."
    )
    description = _listing_extra(ext, listing_md)
    return f"""<!-- generated by `tabmill ship {ext["slug"]}` -->
# Landing page brief — {ext["name"]}

Write one page on **{ext["portfolio_site"]}** at **{url}**.

Open Claude Code in `{site_dir(ext)}` and say: "Write the page in this brief" (attach this
file). Use the `write-lamill-seo-page` skill for title, H1, slug, metadata, schema, FAQ, and
internal links; follow the site's own `AI_AGENTS.md` / `docs/CLAUDE.md` and stack.

## Target

- Primary query: **{keywords[0] if keywords else "‹FILL›"}**
- Secondary: {", ".join(keywords[1:]) or "—"}
- Search intent is the **tool** ("{keywords[0] if keywords else ""}"), not "… chrome extension".

## What the extension does

{ext["single_purpose"]}

{ext["summary"]}
{description}
## Must include

- The page is useful on its own (a real how-to or web tool); the extension is the
  "do it in one click from any page" option.
- {install}
- Hub page: {hub.HUB_BASE}/{ext["slug"]} · Privacy: {hub.PRIVACY_URL}
- Privacy, in plain words: {ext.get("privacy_line") or generate.DEFAULT_PRIVACY}
- "Built by Lamill".

Permissions it asks for (explain them if the page lists permissions):
{perms}

## Never

- Invent numbers, ratings, user counts, reviews, or testimonials.
- Claim features the extension doesn't have (only what's above).
- Use third-party trademarks in the H1/title beyond plain descriptive use.

## After it's live

Commit + push the site (it deploys from `main`), then in the tabmill repo:
`uv run tabmill ship {ext["slug"]}` — confirms the page, records the URL in the recipe,
resubmits the sitemap, and exports to the lamill.io hub.
"""


def _listing_extra(ext: dict[str, Any], listing_md: str | None) -> str:
    """Listing copy the brief doesn't already carry: drops paragraphs repeating the summary or
    single purpose, and unfilled ‹FILL› ones (the generated draft has both)."""
    if not listing_md:
        return ""
    known = {str(ext["summary"]).strip(), str(ext["single_purpose"]).strip()}
    paras = [p.strip() for p in listing.store_text(listing_md).split("\n\n")]
    keep = [p for p in paras if p and p not in known and extension.FILL_MARKER not in p]
    return "".join(f"\n{p}\n" for p in keep)


def write_brief(workspace: Path, slug: str, text: str) -> Path:
    d = listing.store_dir(workspace, slug)
    d.mkdir(parents=True, exist_ok=True)
    path = d / BRIEF_FILE
    path.write_text(text)
    return path


def is_live(url: str) -> int | None:
    try:
        return httpx.get(url, timeout=15, follow_redirects=True).status_code
    except httpx.HTTPError:
        return None


def set_landing_url(tool_dir: Path, slug: str, url: str) -> bool:
    """Set `landing_page_url` in the recipe, keeping the rest of the file as written."""
    path = generate.recipe_dir(tool_dir, slug) / generate.RECIPE_FILE
    text = path.read_text()
    line = f"landing_page_url: {url}"
    new, n = re.subn(r"^landing_page_url:.*$", line, text, count=1, flags=re.M)
    if n == 0:
        new = text.rstrip("\n") + f"\n{line}\n"
    if new == text:
        return False
    path.write_text(new)
    return True


def precheck(ext: dict[str, Any]) -> list[str]:
    problems = []
    if extension.FILL_MARKER in str(ext.get("portfolio_site", "")) or not ext.get("portfolio_site"):
        problems.append("`portfolio_site` is ‹FILL› — no site to put the page on yet")
    if not ext.get("target_keywords") or any(
        extension.FILL_MARKER in str(k) for k in ext.get("target_keywords") or []
    ):
        problems.append("`target_keywords` unfilled")
    return problems
