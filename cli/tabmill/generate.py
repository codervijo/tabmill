"""Generate one extension's managed files from template + recipe (ADR-0008).

    templates/extension/_shared/**      code every template uses (shell, brand, inject, tests)
  + templates/extension/<template>/**   surface code (`*.tmpl` → `{{name}}` rendering)
  + recipes/<slug>/**                   feature code; a file here replaces the template's file
  + generated here                      manifest.gen.json, package.json, src/generated/config.ts,
                                        README.md

Output paths are relative to `extensions/<slug>/`. Written by the sync engine as managed files.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any
from urllib.parse import urlencode, urlsplit, urlunsplit

from . import extension
from .templates import render

RECIPES_DIR = "recipes"
EXT_TEMPLATES_DIR = "templates/extension"
RECIPE_FILE = "extension.yaml"
SHARED_TEMPLATE = "_shared"  # overlaid first, under every surface template
TEMPLATE_SUFFIX = ".tmpl"
LAMILL_URL = "https://lamill.io"
DEFAULT_PRIVACY = "Runs locally — page content never leaves your browser."

# Dev-only toolchain every generated extension builds with (DECISIONS.md § Dependency register).
BASE_DEV_DEPENDENCIES = {
    "wxt": "~0.21.4",
    "typescript": "~5.9.3",
    "vitest": "^5.0.3",
    "@playwright/test": "~1.63.0",
    "@types/node": "^24.0.0",
}
SCRIPTS = {
    "dev": "wxt",
    "build": "wxt build",
    "zip": "wxt zip",
    "postinstall": "wxt prepare",
    "typecheck": "tsc --noEmit",
    "test": "vitest run",
    "smoke": "playwright test",
    "try": "node scripts/try.mjs",
}


class RecipeError(Exception):
    """Recipe missing or invalid; message names the fix."""


def recipe_dir(tool_dir: Path, slug: str) -> Path:
    return tool_dir / RECIPES_DIR / slug


def load_recipe(tool_dir: Path, slug: str) -> dict[str, Any]:
    d = recipe_dir(tool_dir, slug)
    if not (d / RECIPE_FILE).exists():
        raise RecipeError(f"no recipe at {d / RECIPE_FILE} — create it in the tabmill repo first")
    try:
        ext = extension.load_file(d / RECIPE_FILE)
    except extension.ExtensionError as e:
        raise RecipeError(str(e)) from e
    errors = extension.validate(ext, slug)
    errors += [
        f"`{f}` is still ‹FILL› — fill it in {d / RECIPE_FILE}"
        for f in ("name", "summary", "single_purpose")
        if extension.FILL_MARKER in str(ext.get(f, ""))
    ]
    if errors:
        raise RecipeError("; ".join(f"{RECIPE_FILE}: {e}" for e in errors))
    return ext


def with_utm(url: str, *, source: str, medium: str, campaign: str) -> str:
    parts = urlsplit(url)
    utm = urlencode({"utm_source": source, "utm_medium": medium, "utm_campaign": campaign})
    query = f"{parts.query}&{utm}" if parts.query else utm
    return urlunsplit(parts._replace(query=query))


def _config_ts(ext: dict[str, Any]) -> str:
    utm = {"source": ext["slug"], "medium": "extension", "campaign": str(ext["utm_campaign"])}
    values = {
        "name": ext["name"],
        "slug": ext["slug"],
        "singlePurpose": ext["single_purpose"],
        "ctaText": ext["cta_text"],
        "ctaUrl": with_utm(str(ext["cta_url"]), **utm),
        "lamillUrl": with_utm(LAMILL_URL, **utm),
        "privacy": ext.get("privacy_line") or DEFAULT_PRIVACY,
    }
    body = "\n".join(f"  {k}: {json.dumps(v, ensure_ascii=False)}," for k, v in values.items())
    return (
        "// Generated by tabmill from recipes/<slug>/extension.yaml — do not edit (ADR-0008).\n"
        f"export const config = {{\n{body}\n}} as const;\n"
    )


def _package_json(ext: dict[str, Any]) -> str:
    pkg = {
        "name": ext["slug"],
        "version": str(ext["version"]),  # WXT names the zip from this
        "private": True,
        "type": "module",
        "scripts": SCRIPTS,
        "dependencies": dict(sorted((ext.get("dependencies") or {}).items())),
        "devDependencies": dict(
            sorted({**BASE_DEV_DEPENDENCIES, **(ext.get("dev_dependencies") or {})}.items())
        ),
    }
    return json.dumps(pkg, indent=2) + "\n"


def _readme(ext: dict[str, Any]) -> str:
    perms = "\n".join(
        f"- `{p['name']}` — {p['justification']}"
        for key in ("permissions", "optional_permissions", "host_permissions")
        for p in ext.get(key) or []
    )
    analytics = "on (opt-in)" if ext.get("analytics") else "off"
    return f"""<!-- generated by tabmill from recipes/{ext["slug"]}/extension.yaml — do not edit -->
# {ext["name"]}

{ext["summary"]}

**Single purpose:** {ext["single_purpose"]}

## Permissions

{perms}

## Privacy

{ext.get("privacy_line") or DEFAULT_PRIVACY} Analytics: {analytics}.

## Build

Generated by tabmill — change `recipes/{ext["slug"]}/` or the `{ext["template"]}` template in
the tabmill repo, then `tabmill skills sync`. Build: `tabmill build {ext["slug"]}`.

Built by Lamill — {LAMILL_URL}
"""


def _tree(
    root: Path, values: dict[str, str], *, skip: frozenset[str] = frozenset()
) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    if not root.exists():
        return files
    for src in sorted(p for p in root.rglob("*") if p.is_file()):
        rel = str(src.relative_to(root))
        if rel in skip:
            continue
        if rel.endswith(TEMPLATE_SUFFIX):
            files[rel.removesuffix(TEMPLATE_SUFFIX)] = render(src.read_text(), values).encode()
        else:
            files[rel] = src.read_bytes()
    return files


def extension_files(tool_dir: Path, slug: str) -> dict[str, bytes]:
    ext = load_recipe(tool_dir, slug)
    template_root = tool_dir / EXT_TEMPLATES_DIR / str(ext["template"])
    if not template_root.exists():
        raise RecipeError(f"template `{ext['template']}` not implemented yet ({template_root})")
    values = {"name": str(ext["name"]), "slug": slug}
    files = _tree(tool_dir / EXT_TEMPLATES_DIR / SHARED_TEMPLATE, values)
    files.update(_tree(template_root, values))
    files.update(_tree(recipe_dir(tool_dir, slug), values, skip=frozenset({RECIPE_FILE})))
    manifest = extension.to_manifest(ext)
    if ext["template"] == "side-panel":
        # No popup → WXT emits no `action`; the toolbar button must exist to open the panel.
        manifest["action"] = {"default_title": ext["name"]}
    files[extension.GENERATED_MANIFEST] = (json.dumps(manifest, indent=2) + "\n").encode()
    files["package.json"] = _package_json(ext).encode()
    files["src/generated/config.ts"] = _config_ts(ext).encode()
    files["README.md"] = _readme(ext).encode()
    return files
