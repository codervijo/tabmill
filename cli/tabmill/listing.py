"""Store listing draft (`tabmill listing`) and store-image checks.

The CWS API can't set listing text (v2 has upload/publish/status only), so this writes a
Markdown draft to paste into the Developer Dashboard. The `tabmill-store-listing` skill refines
the description; numbers/claims are never invented here.
"""

from __future__ import annotations

import re
import struct
from collections import Counter
from pathlib import Path
from typing import Any

from . import generate, hub

STORE_DIR = ".output/store"
LISTING_FILE = "listing.md"
SCREENSHOT_SIZES = {(1280, 800), (640, 400)}  # developer.chrome.com/docs/webstore/images
KEYWORD_LIMIT = 5  # pp/listing-requirements: a keyword repeated "more than 5 times"
STOPWORDS = {
    "the",
    "a",
    "an",
    "and",
    "or",
    "of",
    "to",
    "in",
    "on",
    "for",
    "with",
    "is",
    "it",
    "this",
    "you",
    "your",
    "page",
    "no",
    "not",
    "be",
    "are",
    "as",
    "by",
    "from",
    "that",
    "when",
    "only",
}


def store_dir(workspace: Path, slug: str) -> Path:
    return workspace / "extensions" / slug / STORE_DIR


def png_size(path: Path) -> tuple[int, int] | None:
    """Width/height from the PNG IHDR chunk; None if not a PNG."""
    head = path.read_bytes()[:24]
    if len(head) < 24 or head[:8] != b"\x89PNG\r\n\x1a\n":
        return None
    width, height = struct.unpack(">II", head[16:24])
    return int(width), int(height)


def image_problems(workspace: Path, slug: str) -> list[str] | None:
    """None if assets were never generated; else a list of size/count problems."""
    d = store_dir(workspace, slug)
    if not d.exists():
        return None
    problems: list[str] = []
    expect = {"icon-128.png": (128, 128), "promo-440x280.png": (440, 280)}
    for name, size in expect.items():
        got = png_size(d / name) if (d / name).exists() else None
        if got != size:
            problems.append(f"{name}: expected {size[0]}×{size[1]}, got {got or 'missing'}")
    shots = sorted(d.glob("screenshot-*.png"))
    if not 1 <= len(shots) <= 5:
        problems.append(f"{len(shots)} screenshots (store needs 1–5)")
    for s in shots:
        if png_size(s) not in SCREENSHOT_SIZES:
            problems.append(f"{s.name}: {png_size(s)} — must be 1280×800 or 640×400")
    return problems


def store_text(markdown: str) -> str:
    """The parts users see on the store page: summary + detailed description sections."""
    keep, out = False, []
    for line in markdown.splitlines():
        if line.startswith("## "):
            keep = line.startswith(("## Summary", "## Detailed description"))
            continue
        if keep:
            out.append(line)
    return "\n".join(out)


def keyword_repeats(markdown: str) -> dict[str, int]:
    text = store_text(markdown)
    words = [w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in STOPWORDS and len(w) > 2]
    return {w: n for w, n in Counter(words).items() if n > KEYWORD_LIMIT}


def listing_markdown(ext: dict[str, Any]) -> str:
    perms = [
        p
        for key in ("permissions", "optional_permissions", "host_permissions")
        for p in ext.get(key) or []
    ]
    perm_rows = "\n".join(f"| `{p['name']}` | {p['justification']} |" for p in perms)
    shots = ext.get("screenshots") or [{"caption": ext["single_purpose"]}]
    captions = "\n".join(f"{i}. {s['caption']}" for i, s in enumerate(shots, 1))
    privacy = ext.get("privacy_line") or generate.DEFAULT_PRIVACY
    data = "None" if not ext.get("analytics") else "‹FILL› — declare the analytics categories"
    return f"""<!-- generated by tabmill listing — draft; refine with tabmill-store-listing -->
# Store listing — {ext["name"]}

## Title ({len(ext["name"])}/75)

{ext["name"]}

## Summary ({len(ext["summary"])}/132)

{ext["summary"]}

## Detailed description

{ext["single_purpose"]}

‹FILL› — how to use it, in 2–4 steps (describe only what the extension actually does).

**Privacy:** {privacy}

**Permissions:** {", ".join(f"`{p['name']}`" for p in perms)} — see the reasons below.

Built by Lamill — {ext["portfolio_site"]}. {ext["cta_text"]}: {ext["cta_url"]}

## Screenshot captions

{captions}

## Category

{ext["store_category"]}

## Privacy practices tab

- **Single purpose:** {ext["single_purpose"]}
- **Remote code:** No
- **Data collected:** {data}
- **Limited Use certifications:** all three (no selling/transfer, no unrelated use,
  no creditworthiness)
- **Privacy policy URL:** {hub.PRIVACY_URL}
- **Support URL:** {hub.SUPPORT_URL}

| Permission | Justification |
|---|---|
{perm_rows}
"""


def write_listing(
    workspace: Path, slug: str, ext: dict[str, Any], *, force: bool = False
) -> tuple[Path, bool]:
    """Create the draft; an existing one (possibly hand-finished) is kept unless `force`.
    Returns (path, written)."""
    d = store_dir(workspace, slug)
    d.mkdir(parents=True, exist_ok=True)
    path = d / LISTING_FILE
    if path.exists() and not force:
        return path, False
    path.write_text(listing_markdown(ext))
    return path, True


RELEASES_DIR = "releases"
RELEASES_IGNORE = "/releases/"


def collect_release(workspace: Path, slug: str, version: str) -> Path:
    """Copy what the dashboard upload needs into `releases/<slug>-<version>/` (one folder).

    The zip, store images, and listing draft otherwise sit under
    `extensions/<slug>/.output/`. Re-running replaces the folder's files. `releases/` is
    added to the workspace .gitignore (the seed .gitignore is written only once).
    """
    import shutil

    out = workspace / RELEASES_DIR / f"{slug}-{version}"
    out.mkdir(parents=True, exist_ok=True)
    built = workspace / "extensions" / slug / ".output"
    for f in [*built.glob(f"{slug}-{version}-*.zip"), *store_dir(workspace, slug).glob("*.png")]:
        shutil.copy2(f, out / f.name)
    listing_md = store_dir(workspace, slug) / LISTING_FILE
    if listing_md.exists():
        shutil.copy2(listing_md, out / LISTING_FILE)
    ignore = workspace / ".gitignore"
    lines = ignore.read_text().splitlines() if ignore.exists() else []
    if RELEASES_IGNORE not in lines:
        with ignore.open("a") as fh:
            fh.write(f"{RELEASES_IGNORE}\n")
    return out
